import os
import sys
import subprocess
import logging
from pathlib import Path
from datetime import datetime, timezone

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger("release_publisher")

COUNTER_FILE = "data/publish_counter.txt"

def count_lines(filepath: str) -> int:
    p = Path(filepath)
    if not p.exists():
        return 0
    with open(p, "r", encoding="utf-8", errors="ignore") as f:
        return len([l for l in f if l.strip() and not l.startswith("#")])

def build_vestranet_notes() -> str:
    """Builds the release notes modeled after VestraNet layout."""
    now_utc = datetime.now(timezone.utc)
