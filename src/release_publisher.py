    # Dynamic line counts
    total_mix = count_lines("all_servers.txt")
    vless = count_lines("servers/vless_servers.txt")
    vmess = count_lines("servers/vmess_servers.txt")
    trojan = count_lines("servers/trojan_servers.txt")
    ss = count_lines("servers/ss_servers.txt")
    hy2 = count_lines("servers/hysteria2_servers.txt")
