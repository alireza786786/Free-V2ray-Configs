def main():
    token = os.getenv("GITHUB_TOKEN")
    if not token:
        logger.warning("GITHUB_TOKEN not available. Skipping GitHub Release.")
        return

    # Check 6th cycle counter (every 3 hours)
    count = 0
    if Path(COUNTER_FILE).exists():
        try:
            count = int(Path(COUNTER_FILE).read_text(encoding="utf-8").strip())
        except Exception:
            count = 0

    if count % 12 != 0:
        logger.info(f"⏳ Cycle #{count % 12}/12: GitHub Release deferred until cycle #12 (every 3 hours).")
        return

    now_utc = datetime.now(timezone.utc)
    tag_name = f"v{now_utc.strftime('%Y.%m.%d-%H%M')}"
    release_title = f"⚡ Goodbaye Core Update: {now_utc.strftime('%Y-%m-%d %H:%M UTC')}"
    notes = build_vestranet_notes()

    # Collect existing files to attach
    candidate_assets = [
        "all_servers.txt",
        "servers/lite.txt",
        "servers/vless_servers.txt",
        "servers/vmess_servers.txt",
        "servers/trojan_servers.txt",
        "servers/ss_servers.txt",
        "servers/hysteria2_servers.txt",
        "servers/tuic_servers.txt",
        "servers/socks5_servers.txt"
    ]
    assets = [f for f in candidate_assets if Path(f).exists()]

    logger.info(f"📦 Publishing GitHub Release '{tag_name}' with {len(assets)} assets...")

    cmd = [
        "gh", "release", "create", tag_name,
        "--title", release_title,
        "--notes", notes,
        "--latest"
    ] + assets

    env = os.environ.copy()
    env["GH_TOKEN"] = token

    try:
        res = subprocess.run(cmd, env=env, capture_output=True, text=True, check=True)
        logger.info(f"✅ Successfully published GitHub Release! {res.stdout.strip()}")
    except subprocess.CalledProcessError as e:
        logger.error(f"❌ Failed to publish Release: {e.stderr.strip()}")

if __name__ == "__main__":
    main()
